String uiString(String text, String languageCode) {
  if (languageCode != 'en') return themeArabic[text] ?? text;
  if (uiEnglish.containsKey(text)) return uiEnglish[text]!;
  final completed = RegExp(r'^(\d+ / \d+) مكتمل$').firstMatch(text);
  if (completed != null) return '${completed[1]} complete';
  final found = RegExp(r'^(\d+) ذكر$').firstMatch(text);
  if (found != null) return '${found[1]} entries';
  final prayers = RegExp(r'^(\d+ / 5) مجموعات سُجّلت اليوم$').firstMatch(text);
  if (prayers != null) return '${prayers[1]} groups recorded today';
  return text;
}

String tr(BuildContext context, String text) =>
    uiString(text, Localizations.localeOf(context).languageCode);

/// Untranslated religious text retains Arabic direction in the English UI.
class UiText extends StatelessWidget {
  const UiText(
    this.data, {
    super.key,
    this.style,
    this.textAlign,
    this.maxLines,
    this.overflow,
    this.textDirection,
  });
  final String data;
  final TextStyle? style;
  final TextAlign? textAlign;
  final int? maxLines;
  final TextOverflow? overflow;
  final TextDirection? textDirection;
  @override
  Widget build(BuildContext context) {
    final value = tr(context, data);
    return Text(
      value,
      style: style,
      textAlign: textAlign,
      maxLines: maxLines,
      overflow: overflow,
      textDirection:
          textDirection ??
          (RegExp(r'[\u0600-\u06ff]').hasMatch(value)
              ? TextDirection.rtl
              : null),
    );
  }
}

